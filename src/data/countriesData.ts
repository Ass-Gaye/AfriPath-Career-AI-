export const DEFAULT_COUNTRY = AFRICAN_COUNTRIES[0]; // The Gambia

export function getCountryByCode(code?: string): CountryConfig {
  if (!code) return DEFAULT_COUNTRY;
  const found = AFRICAN_COUNTRIES.find((c) => c.code.toUpperCase() === code.toUpperCase() || c.name.toLowerCase() === code.toLowerCase());
  return found || DEFAULT_COUNTRY;
}

export function getCountryByName(name?: string): CountryConfig {
  if (!name) return DEFAULT_COUNTRY;
  const found = AFRICAN_COUNTRIES.find((c) => c.name.toLowerCase() === name.toLowerCase() || c.code.toLowerCase() === name.toLowerCase());
  return found || DEFAULT_COUNTRY;
}

export function formatSalary(amountLocal: string, countryCode: string = 'GM', amountUSD?: string): string {
  const country = getCountryByCode(countryCode);
  if (amountUSD && country.code === 'GM') {
    return `${amountLocal} (${amountUSD})`;
  }
  return amountLocal;
}
